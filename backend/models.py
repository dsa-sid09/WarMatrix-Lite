from pydantic import BaseModel, Field
from typing import List, Optional

# ==========================================
# 1. SCENARIO MODELS (Parsed from NL)
# ==========================================

class Scenario(BaseModel):
    mission_objective: str = Field(..., description="The primary goal")
    terrain: str = Field(..., description="Terrain description (e.g., mountainous, urban)")
    weather: str = Field(..., description="Weather conditions")
    enemy_strength: str = Field(..., description="Enemy size/type (e.g., 2 infantry battalions)")
    friendly_assets: List[str] = Field(default_factory=list, description="Friendly units and equipment")
    time_constraint: str = Field(..., description="Time available (e.g., 24 hours)")
    intelligence_gaps: List[str] = Field(default_factory=list, description="What we don't know")


# ==========================================
# 2. COA MODELS (Generated by LLM)
# ==========================================

class COA(BaseModel):
    id: str = Field(..., description="Unique COA ID e.g., COA-1")
    title: str = Field(..., description="Short name e.g., 'Flanking Maneuver'")
    summary: str = Field(..., description="2-sentence summary")
    steps: List[str] = Field(..., description="Sequential action steps")
    required_assets: List[str] = Field(default_factory=list)
    estimated_time: str = Field(..., description="e.g., '12 hours'")
    logistics_plan: str = Field(..., description="Supply and sustainment plan")
    inherent_risks: List[str] = Field(default_factory=list, description="Risks the planner already sees")


# ==========================================
# 3. RED TEAM MODELS
# ==========================================

class RedTeamResult(BaseModel):
    coa_id: str
    persona: str = Field(..., description="Aggressive / Cautious / Supply-Line Cutter")
    adversary_actions: List[str] = Field(..., description="What the enemy does in response")
    vulnerabilities_exploited: List[str] = Field(..., description="Specific weaknesses found")
    success_probability: float = Field(..., ge=0.0, le=1.0, description="0.0 to 1.0")
    confidence: str = Field(..., description="High / Medium / Low")


# ==========================================
# 4. RANKING MODELS (Deterministic Math)
# ==========================================

class RankedCOA(BaseModel):
    coa_id: str
    title: str
    score: float = Field(..., ge=0.0, le=1.0)
    score_breakdown: dict = Field(..., description="Contributions from each factor")
    success_probability: float
    risk_score: float
    logistics_confidence: float
    time_score: float
    rank: int = Field(..., description="1 = best")
    explanation: Optional[str] = Field(None, description="3-sentence reasoning from LLM")


# ==========================================
# 5. REQUEST/RESPONSE WRAPPERS
# ==========================================

class ParseScenarioRequest(BaseModel):
    raw_text: str


class GenerateCOAsRequest(BaseModel):
    scenario: Scenario
    count: int = 5


class RedTeamRequest(BaseModel):
    coa: COA
    scenario: Scenario
    persona: str = "Aggressive"


class RankCOAsRequest(BaseModel):
    coas: List[COA]
    red_team_results: List[RedTeamResult]


class ExplainRequest(BaseModel):
    coa: COA
    ranked: RankedCOA
    scenario: Scenario


class ModifyCOARequest(BaseModel):
    coa: COA
    instruction: str


class ExportBriefRequest(BaseModel):
    scenario: Scenario
    ranked_coas: List[RankedCOA]
    red_team_results: List[RedTeamResult]